/* init_max_iox
 * MAX11311 init register values come from the MAX11300 Configuration Tool (ver 1.1.0.5).
 * The Datasheet (DS) has a specific flowchart for how the registers are programmed,
 * and the time delay between writes. The tool generated sequence is used here.
 */
int init_max_iox(void) {
  char buf[LINE_MAX_LENGTH];

  max_iox.begin(SPI_MOSI_Pin, SPI_MISO_Pin, SPI_SCLK_Pin, SPI_CS_IOX_Pin, MAX11311_CONVERT_Pin);

  uint16_t _dev_id = max_iox.read_register(dev_id);
  if (_dev_id != MAX11311_DEV_ID) {
    snprintf(buf, LINE_MAX_LENGTH, "init_max_iox:id %x", _dev_id);
    oled_print(OLED_LINE_DEBUG, buf, true);
    return -1;
  }

  for (unsigned int i = 0; i < sizeof(init_regs) / sizeof(_init_regs_t); i++) {
    max_iox.write_register(init_regs[i].r, init_regs[i].d);
    delay(1);  // required by MAX11311 programming guide
  }
  return 0;
}

void iox_set(MAX11300::MAX11300_Ports port, bool assert) {
  max_iox.gpio_write(port, assert ? 1 : 0);
}

void iox_leds(bool green, bool yellow, bool red, bool blue) {
  iox_set(IOX_PORT_LED_GREEN, green);
  iox_set(IOX_PORT_LED_YELLOW, yellow);
  iox_set(IOX_PORT_LED_RED, red);
  iox_set(IOX_PORT_LED_BLUE, blue);
}

/* _iox_rpc
 * - common body of the active high IOX GPO RPCs
 */
static String _iox_rpc(const char *method, MAX11300::MAX11300_Ports port, bool assert) {
  JsonDocument &doc = rpc_begin(method);  // always first line of RPC API
  iox_set(port, assert);
  doc["result"]["assert"] = assert;
  doc["result"]["level"] = assert;
  return rpc_response(doc);  // always the last line of RPC API
}

