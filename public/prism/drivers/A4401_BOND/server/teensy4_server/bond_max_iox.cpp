/* bond_ldo_set
 *  - Header 1 LDO output voltage, LDO_MIN_MV..LDO_MAX_MV, see bond_max_iox.h
 *  - the LDO is enabled by the Header 1 GPO on port 1
 */
String bond_ldo_set(uint16_t mv) {
  JsonDocument &doc = rpc_begin(__func__);  // always first line of RPC API
  if (mv < LDO_MIN_MV || mv > LDO_MAX_MV) return rpc_error(doc, "600 <= mv <= 3900, invalid parameter");

  // LDO_ADJ = 2 * VFB - (VOUT - VFB) * R47 / R46
  int32_t adj_mv = 2 * LDO_VFB_MV - ((int32_t)mv - LDO_VFB_MV) * LDO_R47_OHMS / LDO_R46_OHMS;
  uint16_t code = (uint16_t)((adj_mv * 4096 + IOX_DAC_FULL_MV / 2) / IOX_DAC_FULL_MV);
  max_iox.single_ended_dac_write(IOX_PORT_LDO_ADJ, code);

  doc["result"]["mv"] = mv;
  doc["result"]["dac_raw"] = code;
  return rpc_response(doc);  // always the last line of RPC API
}
